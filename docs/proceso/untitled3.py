import numpy as np
import time
import matplotlib.pyplot as plt
from itertools import permutations

# --- LIBRERÍAS DE QISKIT (CUÁNTICO) ---
from qiskit_optimization import QuadraticProgram
from qiskit_algorithms import QAOA
from qiskit_algorithms.optimizers import COBYLA
from qiskit.primitives import StatevectorSampler
from qiskit_optimization.algorithms import MinimumEigenOptimizer

print("=== CONFIGURANDO EL ENTORNO Y INICIALIZANDO DATOS ===")

# ==========================================
# 1. DEFINICIÓN DE DATOS GENERALES (N=3)
# ==========================================
brigadas = ["Medica", "Logistica", "Rescate"]
zonas = ["Piura", "Chosica", "Tumbes"]
N = len(brigadas)

# Matriz de Sinergias/Flujo (Sinergia entre brigadas) - Corregida
F = np.array([
    [0, 3, 2],
    [3, 0, 5],
    [2, 5, 0]
])

# Matriz de Tiempos/Distancia (Tiempo en horas entre zonas) - Corregida
D = np.array([
    [0, 10, 8],
    [10, 0, 15],
    [8, 15, 0]
])


# ==========================================
# 2. EJECUCIÓN CLÁSICA (EJECUCIÓN 1)
# ==========================================
print("\nEjecutando Modelo Clásico (Fuerza Bruta Exacta)...")
inicio_clasico = time.perf_counter()

mejor_costo_clasico = float('inf')
mejor_asignacion_clasica = None

# Probar las 3! = 6 combinaciones posibles
for perm in permutations(range(N)):
    costo_actual = 0
    for i in range(N):
        for k in range(N):
            j = perm[i]
            l = perm[k]
            costo_actual += F[i, k] * D[j, l]

    costo_real = costo_actual / 2.0  # Evitar doble conteo por simetría
    if costo_real < mejor_costo_clasico:
        mejor_costo_clasico = costo_real
        mejor_asignacion_clasica = perm

fin_clasico = time.perf_counter()
tiempo_clasico = fin_clasico - inicio_clasico
print(f"-> Clásico completado en {tiempo_clasico:.6f} segundos.")

# ==========================================
# 3. EJECUCIÓN CUÁNTICA HÍBRIDA (EJECUCIÓN 2)
# ==========================================
print("\nEjecutando Modelo Cuántico Híbrido (QAOA con Qiskit)...")
inicio_cuantico = time.perf_counter()

# Configurar el programa cuadrático en Qiskit
qp = QuadraticProgram()

# Crear las variables binarias x_i_j
for i in range(N):
    for j in range(N):
        qp.binary_var(name=f"x_{i}_{j}")

# Construir la función objetivo matemática
quadratic_terms = {}
for i in range(N):
    for k in range(N):
        if i == k: continue
        for j in range(N):
            for l in range(N):
                if j == l: continue
                coef = F[i, k] * D[j, l]
                if coef != 0:
                    quadratic_terms[(f"x_{i}_{j}", f"x_{k}_{l}")] = coef / 2.0

qp.minimize(quadratic=quadratic_terms)

# Añadir restricciones de asignación única (filas y columnas)
for i in range(N):
    qp.linear_constraint(linear={f"x_{i}_{j}": 1 for j in range(N)}, sense="==", rhs=1)
for j in range(N):
    qp.linear_constraint(linear={f"x_{i}_{j}": 1 for i in range(N)}, sense="==", rhs=1)

# Configurar los solucionadores cuánticos híbridos utilizando COBYLA
sampler = StatevectorSampler()
optimizer = COBYLA(maxiter=100)
qaoa = QAOA(sampler=sampler, optimizer=optimizer, reps=2)
opt_qaoa = MinimumEigenOptimizer(qaoa)

# Resolver el Hamiltoniano QUBO
resultado_cuantico = opt_qaoa.solve(qp)
mejor_costo_cuantico = resultado_cuantico.fval

fin_cuantico = time.perf_counter()
tiempo_cuantico = fin_cuantico - inicio_cuantico
print(f"-> Cuántico completado en {tiempo_cuantico:.6f} segundos.")

# ==========================================
# 4. CÁLCULO DE MÉTRICAS Y COMPARATIVA
# ==========================================
print("\n" + "=" * 40)
print("=== CONSOLIDADO DE RESULTADOS TOTALES ===")
print("=" * 40)

print(f"Costo Óptimo Clásico: {mejor_costo_clasico} horas")
print(f"Costo Óptimo Cuántico: {mejor_costo_cuantico} horas")

# Calcular el Gap Matemático de Aproximación
gap_porcentaje = 100 * (mejor_costo_cuantico - mejor_costo_clasico) / mejor_costo_clasico
print(f"Gap de Calidad Cuántica: {gap_porcentaje:.2f}%")

print(f"\nTiempo de Cálculo Clásico: {tiempo_clasico:.6f} segundos")
print(f"Tiempo de Cálculo Cuántico (Simulado): {tiempo_cuantico:.6f} segundos")

# Desglose de asignación clásica ganadora
print("\nAsignación Sugerida (Fuerza Bruta):")
for i, z_idx in enumerate(mejor_asignacion_clasica):
    print(f"  * [{brigadas[i]}] desplegada en -> [{zonas[z_idx]}]")

# ==========================================
# 5. VISUALIZACIÓN DE RENDIMIENTO
# ==========================================
fig, ax = plt.subplots(figsize=(6, 4))
modelos = ['Clásico (Exacto)', 'Cuántico (QAOA Simulado)']
tiempos = [tiempo_clasico, tiempo_cuantico]

barras = ax.bar(modelos, tiempos, color=['lightcoral', 'teal'], width=0.5)
ax.set_ylabel('Tiempo de Ejecución (segundos)')
ax.set_title('Comparativa de Rendimiento de Cómputo (N=3)')

for barra in barras:
    yval = barra.get_height()
    ax.text(barra.get_x() + barra.get_width() / 2, yval, f"{yval:.4f} s", ha='center', va='bottom', fontweight='bold')

plt.tight_layout()
plt.show()