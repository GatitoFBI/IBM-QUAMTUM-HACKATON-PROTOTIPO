import numpy as np
import time
import math
import matplotlib.pyplot as plt
from itertools import permutations

from qiskit_optimization import QuadraticProgram
from qiskit_optimization.converters import QuadraticProgramToQubo
from qiskit_optimization.algorithms import MinimumEigenOptimizer
from qiskit_algorithms import NumPyMinimumEigensolver, QAOA
from qiskit_algorithms.optimizers import COBYLA
from qiskit.primitives import StatevectorSampler

# ==========================================
# CONFIGURACIÓN DEL EXPERIMENTO
# ==========================================
N_CLASICO = range(3, 10)   # el clásico se prueba de N=3 a N=9
N_QUBO = [3, 4]            # QUBO exacto (N=5 ya pide ~25 qubits: muy pesado)
N_QAOA = [3, 4]            # QAOA híbrido (N^2 qubits simulados)
SEMILLA = 42


def generar_datos(n, semilla=SEMILLA):
    """Matrices simétricas F (sinergias) y D (horas), diagonal 0."""
    rng = np.random.default_rng(semilla + n)
    F = rng.integers(1, 10, size=(n, n))
    D = rng.integers(5, 20, size=(n, n))
    F = np.triu(F, 1); F = F + F.T
    D = np.triu(D, 1); D = D + D.T
    return F, D


# ==========================================
# MODELO CLÁSICO
# ==========================================
def resolver_clasico(F, D):
    n = len(F)
    mejor, mejor_perm = float("inf"), None
    for perm in permutations(range(n)):
        p = list(perm)
        costo = (F * D[np.ix_(p, p)]).sum() / 2.0
        if costo < mejor:
            mejor, mejor_perm = costo, perm
    return mejor, mejor_perm


# ==========================================
# CONSTRUCCIÓN DEL PROBLEMA CUADRÁTICO
# ==========================================
def construir_qp(F, D):
    n = len(F)
    qp = QuadraticProgram()
    for i in range(n):
        for j in range(n):
            qp.binary_var(name=f"x_{i}_{j}")

    q = {}
    for i in range(n):
        for k in range(n):
            if i == k:
                continue
            for j in range(n):
                for l in range(n):
                    if j == l:
                        continue
                    coef = F[i, k] * D[j, l]
                    if coef != 0:
                        q[(f"x_{i}_{j}", f"x_{k}_{l}")] = coef / 2.0
    qp.minimize(quadratic=q)

    for i in range(n):
        qp.linear_constraint({f"x_{i}_{j}": 1 for j in range(n)}, "==", 1)
    for j in range(n):
        qp.linear_constraint({f"x_{i}_{j}": 1 for i in range(n)}, "==", 1)
    return qp


def resolver_con(solver, qp):
    """Convierte a QUBO y resuelve con el solver indicado."""
    conv = QuadraticProgramToQubo()
    qubo = conv.convert(qp)
    res = solver.solve(qubo)
    x = conv.interpret(res.x)
    return qp.objective.evaluate(x), qp.is_feasible(x)


# ==========================================
# EJECUCIÓN
# ==========================================
t_clasico, costos_clasico = {}, {}
t_qubo, t_qaoa = {}, {}
calidad = {}

print("=== CLÁSICO ===")
for n in N_CLASICO:
    F, D = generar_datos(n)
    t0 = time.perf_counter()
    costo, _ = resolver_clasico(F, D)
    t_clasico[n] = time.perf_counter() - t0
    costos_clasico[n] = costo
    print(f"N={n}: {t_clasico[n]:.6f} s  (costo {costo})")

print("\n=== QUBO EXACTO (NumPyMinimumEigensolver) ===")
for n in N_QUBO:
    F, D = generar_datos(n)
    qp = construir_qp(F, D)
    t0 = time.perf_counter()
    costo, ok = resolver_con(MinimumEigenOptimizer(NumPyMinimumEigensolver()), qp)
    t_qubo[n] = time.perf_counter() - t0
    calidad[("QUBO", n)] = (costo, ok)
    print(f"N={n} ({n*n} qubits): {t_qubo[n]:.4f} s  (costo {costo}, factible={ok})")

print("\n=== HÍBRIDO CUÁNTICO-CLÁSICO (QAOA + COBYLA) ===")
for n in N_QAOA:
    F, D = generar_datos(n)
    qp = construir_qp(F, D)
    try:
        qaoa = QAOA(sampler=StatevectorSampler(), optimizer=COBYLA(maxiter=50), reps=1)
        t0 = time.perf_counter()
        costo, ok = resolver_con(MinimumEigenOptimizer(qaoa), qp)
        t_qaoa[n] = time.perf_counter() - t0
        calidad[("QAOA", n)] = (costo, ok)
        gap = 100 * (costo - costos_clasico[n]) / costos_clasico[n]
        print(f"N={n} ({n*n} qubits): {t_qaoa[n]:.4f} s  (costo {costo}, factible={ok}, gap={gap:.1f}%)")
    except Exception as e:
        print(f"QAOA N={n} falló: {e}")

print("\n=== POR QUÉ NO ESCALA LA SIMULACIÓN ===")
for n in range(3, 9):
    qubits = n * n
    mem_gb = (2 ** qubits) * 16 / 1e9
    print(f"N={n}: {qubits:>2} qubits -> statevector ~ {mem_gb:,.4f} GB | fuerza bruta: {math.factorial(n):,} permutaciones")

# ==========================================
# GRÁFICO
# ==========================================
fig, ax = plt.subplots(figsize=(8, 5))
ax.plot(list(t_clasico), list(t_clasico.values()), "o-", color="lightcoral", label="Clásico (fuerza bruta)")
if t_qubo:
    ax.plot(list(t_qubo), list(t_qubo.values()), "s-", color="teal", label="QUBO exacto")
if t_qaoa:
    ax.plot(list(t_qaoa), list(t_qaoa.values()), "^-", color="purple", label="QAOA híbrido")
ax.set_yscale("log")
ax.set_xlabel("N (brigadas / zonas)")
ax.set_ylabel("Tiempo (s, escala log)")
ax.set_title("Escalado de tiempos: clásico vs cuántico simulado")
ax.legend()
ax.grid(True, which="both", alpha=0.3)
plt.tight_layout()
plt.show()