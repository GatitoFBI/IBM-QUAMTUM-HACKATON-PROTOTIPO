import math
import time
import warnings
warnings.filterwarnings("ignore", category=DeprecationWarning)
import numpy as np
import matplotlib.pyplot as plt
from itertools import permutations

from qiskit import QuantumCircuit
from qiskit.circuit.library import Diagonal
from qiskit.quantum_info import Statevector

# ==========================================
# CONFIGURACIÓN
# ==========================================
N_LISTA = [3, 4, 5, 6]   # tamaños a probar (N=7 ya usa 13 qubits y tarda bastante)
REPETICIONES = 5         # veces que se repite Grover por cada N (es probabilístico)
SEMILLA = 42
rng_global = np.random.default_rng(SEMILLA)


def generar_datos(n):
    """Matrices simétricas F (sinergias) y D (horas), diagonal 0.
    Reemplaza esta función por tus matrices originales si quieres."""
    rng = np.random.default_rng(SEMILLA + n)
    F = np.triu(rng.integers(1, 10, size=(n, n)), 1)
    D = np.triu(rng.integers(5, 20, size=(n, n)), 1)
    return F + F.T, D + D.T


def costo_perm(F, D, perm):
    p = list(perm)
    return (F * D[np.ix_(p, p)]).sum() / 2.0


# ==========================================
# MODELO CLÁSICO (fuerza bruta)
# ==========================================
def resolver_clasico(F, D):
    mejor, mejor_perm, evaluaciones = float("inf"), None, 0
    for perm in permutations(range(len(F))):
        c = costo_perm(F, D, perm)
        evaluaciones += 1
        if c < mejor:
            mejor, mejor_perm = c, perm
    return mejor, mejor_perm, evaluaciones


# ==========================================
# GROVER ADAPTIVE SEARCH (Dürr-Høyer / BBHT)
# ==========================================
def circuito_grover(n_qubits, marcados, iteraciones):
    """H^n  +  k x [oraculo de fase + difusion]."""
    fase = np.ones(2 ** n_qubits, dtype=complex)
    fase[list(marcados)] = -1                      # oraculo: marca estados con costo < umbral
    oraculo = Diagonal(fase)

    qc = QuantumCircuit(n_qubits)
    qc.h(range(n_qubits))
    for _ in range(iteraciones):
        qc.append(oraculo, range(n_qubits))
        qc.h(range(n_qubits))                      # difusion: 2|s><s| - I
        qc.x(range(n_qubits))
        qc.h(n_qubits - 1)
        qc.mcx(list(range(n_qubits - 1)), n_qubits - 1) if n_qubits > 1 else qc.z(0)
        qc.h(n_qubits - 1)
        qc.x(range(n_qubits))
        qc.h(range(n_qubits))
    return qc


def grover_adaptive(costos, rng, lam=6 / 5):
    """Busca el minimo de `costos` (lista indexada por permutacion).
    Devuelve (indice, costo, llamadas_al_oraculo)."""
    M = len(costos)
    n_q = max(1, math.ceil(math.log2(M)))
    presupuesto = 22.5 * math.sqrt(M) + 1.4 * math.log2(M) ** 2

    y = int(rng.integers(0, M))                    # umbral inicial aleatorio
    m, llamadas = 1.0, 0
    while llamadas < presupuesto:
        marcados = [i for i in range(M) if costos[i] < costos[y]]
        if not marcados:                           # ya es el minimo (en la practica
            break                                  # se detecta por presupuesto agotado)
        j = int(rng.integers(0, math.ceil(m)))     # numero aleatorio de iteraciones
        qc = circuito_grover(n_q, marcados, j)
        probs = Statevector(qc).probabilities()
        salida = int(rng.choice(len(probs), p=probs / probs.sum()))   # "medicion"
        llamadas += max(j, 1)
        if salida < M and costos[salida] < costos[y]:
            y, m = salida, 1.0                     # mejoramos el umbral
        else:
            m = min(lam * m, math.sqrt(M))
    return y, costos[y], llamadas


# ==========================================
# EJECUCION
# ==========================================
res = {"n": [], "t_cl": [], "t_gr": [], "ev_cl": [], "q_gr": [], "exito": [], "qubits": []}

for n in N_LISTA:
    F, D = generar_datos(n)

    t0 = time.perf_counter()
    mejor, perm_opt, ev = resolver_clasico(F, D)
    t_cl = time.perf_counter() - t0

    # Tabla de costos que usa el oraculo (en simulacion se precalcula)
    perms = list(permutations(range(n)))
    costos = [costo_perm(F, D, p) for p in perms]

    rng = np.random.default_rng(SEMILLA)
    tiempos, llam, aciertos = [], [], 0
    for _ in range(REPETICIONES):
        t0 = time.perf_counter()
        idx, c, q = grover_adaptive(costos, rng)
        tiempos.append(time.perf_counter() - t0)
        llam.append(q)
        aciertos += int(abs(c - mejor) < 1e-9)

    res["n"].append(n)
    res["t_cl"].append(t_cl)
    res["t_gr"].append(np.mean(tiempos))
    res["ev_cl"].append(ev)
    res["q_gr"].append(np.mean(llam))
    res["exito"].append(100 * aciertos / REPETICIONES)
    res["qubits"].append(max(1, math.ceil(math.log2(len(perms)))))

    print(f"N={n} | qubits={res['qubits'][-1]} | clasico: {t_cl:.5f}s, {ev} evaluaciones | "
          f"Grover (simulado): {np.mean(tiempos):.3f}s, ~{np.mean(llam):.0f} llamadas al oraculo | "
          f"acierto: {res['exito'][-1]:.0f}% | optimo={mejor} en {perm_opt}")

# ==========================================
# GRAFICOS
# ==========================================
fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11, 4.5))

ax1.plot(res["n"], res["t_cl"], "o-", color="lightcoral", label="Clásico (fuerza bruta)")
ax1.plot(res["n"], res["t_gr"], "^-", color="purple", label="Grover (simulado)")
ax1.set_yscale("log")
ax1.set_xlabel("N")
ax1.set_ylabel("Tiempo (s, escala log)")
ax1.set_title("Tiempo de cómputo")
ax1.legend()
ax1.grid(True, which="both", alpha=0.3)

ax2.plot(res["n"], res["ev_cl"], "o-", color="lightcoral", label="Clásico: evaluaciones (N!)")
ax2.plot(res["n"], res["q_gr"], "^-", color="purple", label="Grover: llamadas al oráculo")
ax2.set_yscale("log")
ax2.set_xlabel("N")
ax2.set_ylabel("Consultas (escala log)")
ax2.set_title("Complejidad de consultas")
ax2.legend()
ax2.grid(True, which="both", alpha=0.3)

plt.tight_layout()
plt.show()