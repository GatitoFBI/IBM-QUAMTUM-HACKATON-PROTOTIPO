import numpy as np
import time
import matplotlib.pyplot as plt
from itertools import permutations

# --- LIBRERÍAS DE QISKIT (QUBO) ---
from qiskit_optimization import QuadraticProgram
from qiskit_optimization.converters import QuadraticProgramToQubo
from qiskit_optimization.algorithms import MinimumEigenOptimizer
from qiskit_algorithms import NumPyMinimumEigensolver

print("=== INICIALIZANDO DATOS ===")

# ==========================================
# 1. DEFINICIÓN DE DATOS GENERALES (N=3)
# ==========================================
brigadas = ["Medica", "Logistica", "Rescate"]
zonas = ["Piura", "Chosica", "Tumbes"]
N = len(brigadas)

# Matriz de Sinergias/Flujo (simétrica)
# OJO: reemplaza los valores de muestra (3 y 10) por los de tu archivo original
F = np.array([
    [0, 3, 2],
    [3, 0, 5],
    [2, 5, 0]
])

# Matriz de Tiempos/Distancia en horas (simétrica)
D = np.array([
    [0, 10, 8],
    [10, 0, 15],
    [8, 15, 0]
])

# ==========================================
# 2. MODELO CLÁSICO (FUERZA BRUTA EXACTA)
# ==========================================
print("\nEjecutando Modelo Clásico (Fuerza Bruta Exacta)...")
inicio_clasico = time.perf_counter()

mejor_costo_clasico = float('inf')
mejor_asignacion_clasica = None

for perm in permutations(range(N)):
    costo_actual = 0
    for i in range(N):
        for k in range(N):
            costo_actual += F[i, k] * D[perm[i], perm[k]]

    costo_real = costo_actual / 2.0  # Evitar doble conteo por simetría
    if costo_real < mejor_costo_clasico:
        mejor_costo_clasico = costo_real
        mejor_asignacion_clasica = perm

tiempo_clasico = time.perf_counter() - inicio_clasico
print(f"-> Clásico completado en {tiempo_clasico:.6f} segundos.")

# ==========================================
# 3. MODELO QUBO
# ==========================================
print("\nEjecutando Modelo QUBO...")
inicio_qubo = time.perf_counter()

# 3.1 Programa cuadrático con variables binarias x_i_j
qp = QuadraticProgram()
for i in range(N):
    for j in range(N):
        qp.binary_var(name=f"x_{i}_{j}")

# 3.2 Función objetivo cuadrática
quadratic_terms = {}
for i in range(N):
    for k in range(N):
        if i == k:
            continue
        for j in range(N):
            for l in range(N):
                if j == l:
                    continue
                coef = F[i, k] * D[j, l]
                if coef != 0:
                    quadratic_terms[(f"x_{i}_{j}", f"x_{k}_{l}")] = coef / 2.0

qp.minimize(quadratic=quadratic_terms)

# 3.3 Restricciones de asignación única (filas y columnas)
for i in range(N):
    qp.linear_constraint(linear={f"x_{i}_{j}": 1 for j in range(N)}, sense="==", rhs=1)
for j in range(N):
    qp.linear_constraint(linear={f"x_{i}_{j}": 1 for i in range(N)}, sense="==", rhs=1)

# 3.4 Conversión a QUBO (las restricciones pasan a ser penalizaciones)
conversor = QuadraticProgramToQubo()
qubo = conversor.convert(qp)
print(f"   Variables del QUBO: {qubo.get_num_binary_vars()}")

# 3.5 Resolver el QUBO (minimización exacta del Hamiltoniano asociado)
solver_qubo = MinimumEigenOptimizer(NumPyMinimumEigensolver())
resultado_qubo = solver_qubo.solve(qubo)

# 3.6 Interpretar la solución en el problema original
resultado_original = conversor.interpret(resultado_qubo.x)
x_qubo = np.array(resultado_original).reshape(N, N)
mejor_costo_qubo = qp.objective.evaluate(resultado_original)
es_factible = qp.is_feasible(resultado_original)

tiempo_qubo = time.perf_counter() - inicio_qubo
print(f"-> QUBO completado en {tiempo_qubo:.6f} segundos.")

# ==========================================
# 4. MÉTRICAS Y COMPARATIVA
# ==========================================
print("\n" + "=" * 40)
print("=== CONSOLIDADO DE RESULTADOS ===")
print("=" * 40)

print(f"Costo Óptimo Clásico: {mejor_costo_clasico} horas")
print(f"Costo Óptimo QUBO:    {mejor_costo_qubo} horas")
print(f"Solución QUBO factible: {es_factible}")

if mejor_costo_clasico != 0:
    gap = 100 * (mejor_costo_qubo - mejor_costo_clasico) / mejor_costo_clasico
    print(f"Gap de Calidad QUBO: {gap:.2f}%")

print(f"\nTiempo Clásico: {tiempo_clasico:.6f} segundos")
print(f"Tiempo QUBO:    {tiempo_qubo:.6f} segundos")
if tiempo_clasico > 0:
    print(f"QUBO es {tiempo_qubo / tiempo_clasico:.1f} veces el tiempo del clásico")

print("\nAsignación Clásica:")
for i, z_idx in enumerate(mejor_asignacion_clasica):
    print(f"  * [{brigadas[i]}] desplegada en -> [{zonas[z_idx]}]")

print("\nAsignación QUBO:")
for i in range(N):
    z_idx = int(np.argmax(x_qubo[i]))
    print(f"  * [{brigadas[i]}] desplegada en -> [{zonas[z_idx]}]")

# ==========================================
# 5. VISUALIZACIÓN
# ==========================================
fig, ax = plt.subplots(figsize=(6, 4))
modelos = ['Clásico (Exacto)', 'QUBO']
tiempos = [tiempo_clasico, tiempo_qubo]

barras = ax.bar(modelos, tiempos, color=['lightcoral', 'teal'], width=0.5)
ax.set_ylabel('Tiempo de Ejecución (segundos)')
ax.set_title('Comparativa de Tiempos: Clásico vs QUBO (N=3)')
ax.set_yscale('log')  # escala log porque la diferencia suele ser de órdenes de magnitud

for barra in barras:
    yval = barra.get_height()
    ax.text(barra.get_x() + barra.get_width() / 2, yval, f"{yval:.4f} s",
            ha='center', va='bottom', fontweight='bold')

plt.tight_layout()
plt.show()